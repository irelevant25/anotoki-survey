-- WHAT THE SITE SAYS TO SOMEBODY TAKING A SURVEY
--
-- 002 made the tables; these are the words that go in them. Everything the
-- site itself says where people take surveys - the top bar, the list of open
-- surveys, the survey page in every state, the rule and the problem under a
-- question, the About-you step, the pages drawn when the site cannot run -
-- is a key here, with its English and its Slovak string. The admin area has
-- none: it stays English, written in its templates. A survey's own texts are
-- not here either: they are the survey's.
--
-- The code names a key and the page shows its string; a key with no row
-- shows as the key itself, so the list below and the frontend are held
-- together by a test (tests/unit/translations.test.php): every key the
-- frontend asks for is here, and every key here is asked for.
--
-- The description is all a translator has: where the string is shown and
-- what its {placeholders} stand for. The English string fixes which
-- placeholders a key has - the code fills exactly those - so English may be
-- reworded in the admin area but never gain or lose one, and another
-- language may use only those.
--
-- Keys ending in .one, .few and .other are the forms of one plural, asked for
-- by the family's name with a {count}: Slovak says "1 otázka", "3 otázky",
-- "12 otázok". English never picks .few; it says there what .other says,
-- because it is what a language with no string of its own falls back to.
-- Slovak speaks to the reader formally here (Vy, with its capital), unlike
-- the other anotoki sites.
--
-- Every insert steps aside for a row that is already there: a string
-- reworded in the admin area is the owner's and is never written over. So a
-- string added or reworded after this is a migration of its own, never an
-- edit of this file.
--
-- One string on a line, an apostrophe written twice and nothing else
-- escaped: that is all the statement splitter (api/migration_runner.php)
-- knows of a string.
-----------------------------------------------------------

